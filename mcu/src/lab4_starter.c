int main(void) {
    configureClock();
    RCC->APB2ENR |= (0b11 << 16); // enable PLL clock for timers 15 and 16

    int pitch = 0;
    int duration = 0;
    int SR15 = 0;
    int SR16 = 0;
    initTIM15();
    initTIM16();

    pinMode(12, GPIO_OUTPUT);
    for (int i = 0; i < (sizeof(notes)/sizeof(notes[0])); i++) {
        pitch = notes[i][0];
        duration = notes[i][1];
        SR15 = configureTIM15(duration, pitch);
        SR16 = configureTIM16(pitch, SR15);
        while(~SR15 & 1){
            digitalWrite(12, SR16);
        }
    }
}