int main(void) {
   configureFlash();
   configureClock();

   RCC->APB2ENR |= (0b11 << 16); // enable clock domain for timers 15 and 16
   RCC->AHB2ENR |= (1 << 0); // enable GPIOA
   
   initTIM15(); // initialize timer 15
   initTIM16(); // initialize timer 16

   pinMode(PIN_NUM, GPIO_ALT); // using alternative function for GPIO

   GPIO->AFRL |= (0b1110 << 24); // configure to TIM16 CH1

   for (int i = 0; i < (sizeof(notes)/sizeof(notes[0])); i++) {
       configureTIM16(notes[i][0]); // start pitching
       configureTIM15(notes[i][1]); // start duration
   }
}